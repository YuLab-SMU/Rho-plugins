import { test } from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { Resources, Documents, checkRequirements, planExecution, verifyArtifacts, digest } from '../../dist/index.js';
const ref = r => ({ id: r.id, version: r.version });
const declaration = (file, key = 'sample_id', namespace = 'samples') => ({ path: file, kind: 'table', format: { encoding: 'csv', columns: [{ name: key, type: 'string', nullValues: [] }, { name: 'label', type: 'string', nullValues: [] }, { name: 'value', type: 'number', nullValues: ['', 'NA'] }], key: { column: key, namespace } } });
test('declared types retain 001 and literal NA; joins retain nulls, namespaces and both input versions', async () => {
  const root = await fs.mkdtemp(path.join(tmpdir(), 'rho-data-'));
  const data = new Resources(root, 'test', { maxPageRows: 3, maxPoints: 1 });
  await fs.writeFile(path.join(root, 'a.csv'), 'sample_id,label,value\n001,NA,2\n002,other,NA\n');
  const a = await data.register('a.csv', { operationId: 'a' }, 'partial', {}, declaration('a.csv'));
  await fs.writeFile(path.join(root, 'b.csv'), 'record,label,value\n001,NA,1.2\n003,third,9\n');
  const b = await data.register('b.csv', { operationId: 'b' }, 'available', {}, declaration('b.csv', 'record', 'other-samples'));
  const page = await data.page(ref(a), 0, 3, { column: 'value', direction: 'asc' });
  assert.equal(page.rows[0].sample_id, '001'); assert.equal(page.rows[0].label, 'NA'); assert.equal(page.rows[1].value, null);
  await assert.rejects(data.page(ref(a), 0, 4), { kind: 'limit' });
  await assert.rejects(data.page(ref(a), 0, 2, undefined, { column: 'value', op: 'gt', value: '5' }), { kind: 'invalid' });
  const options = { leftKey: 'sample_id', rightKey: 'record', leftNamespace: 'samples', rightNamespace: 'other-samples', mapping: 'equal-string', leftField: 'value', rightField: 'value', join: 'full' };
  await assert.rejects(data.compare(ref(a), ref(b), { ...options, rightNamespace: 'samples' }), { kind: 'condition' });
  const c = await data.compare(ref(a), ref(b), options), joined = await data.page(ref(c), 0, 3);
  assert.deepEqual(joined.rows, [{ key: '001', x: 2, y: 1.2 }, { key: '002', x: null, y: null }, { key: '003', x: null, y: 9 }]);
  assert.deepEqual(c.provenance.inputs, [ref(a), ref(b)]);
  assert.equal((await data.plot(ref(c), 'x', 'y')).downsampled, true);
  await fs.appendFile(path.join(root, 'b.csv'), '004,fourth,4\n');
  await assert.rejects(data.page(ref(c), 0, 3), { kind: 'stale' });
});
test('a completion sidecar verifies immutable producer bytes and rejects escaping output declarations', async () => {
  const root = await fs.mkdtemp(path.join(tmpdir(), 'rho-inventory-'));
  const resources = new Resources(root, 'test'), documents = new Documents(root);
  const d = await documents.open('script.R', 'test');
  const artifact = { path: 'producer.txt', kind: 'file', format: { mimeType: 'text/plain' } };
  const input = { script: { kind: 'buffer', documentId: d.id, version: d.version }, args: [], requirements: [], artifacts: [artifact], completion: 'inventory.json' };
  const environment = { rscript: 'Rscript', libraryPaths: [] };
  await assert.rejects(planExecution(root, { ...input, artifacts: [{ ...artifact, path: '../outside.txt' }] }, 'invalid', environment, resources, documents), { kind: 'scope' });
  const plan = await planExecution(root, input, 'operation', environment, resources, documents);
  await fs.mkdir(path.join(root, plan.output));
  const bytes = Buffer.from('original producer bytes');
  await fs.writeFile(path.join(root, plan.output, artifact.path), bytes);
  await fs.writeFile(path.join(root, plan.completion), JSON.stringify({ schemaVersion: 1, complete: true, artifacts: [{ path: artifact.path, bytes: bytes.length, sha256: digest(bytes) }] }));
  const run = { plan, operationId: 'operation', projectId: 'test', action: 'r.execute', actionVersion: '0.2.0', core: { caller: 'test', requestId: 'original' } };
  const facts = await verifyArtifacts(root, run, resources);
  assert.equal(facts.integrity.state, 'verified'); assert.equal(facts.domain.state, 'unchecked');
  assert.deepEqual(await fs.readdir(path.join(root, plan.output)), ['producer.txt']);
  await fs.writeFile(path.join(root, plan.output, artifact.path), 'changed');
  await assert.rejects(verifyArtifacts(root, run, resources), { kind: 'condition' });
  await fs.unlink(path.join(root, plan.output, artifact.path));
  await fs.writeFile(path.join(root, 'outside.txt'), bytes);
  await fs.symlink(path.join(root, 'outside.txt'), path.join(root, plan.output, artifact.path));
  await assert.rejects(verifyArtifacts(root, run, resources), { kind: 'scope' });
});
test('unkeyed tables are readable, keys are never fabricated and declaration changes have distinct identities', async () => {
  const root = await fs.mkdtemp(path.join(tmpdir(), 'rho-unkeyed-')), data = new Resources(root, 'test');
  await fs.writeFile(path.join(root, 'a.csv'), 'sample_id,label,value\n001,NA,2\n001,other,3\n');
  const d = declaration('a.csv'); d.format.key = null;
  const a = await data.register('a.csv', { operationId: 'a' }, 'available', {}, d);
  assert.equal((await data.rows(ref(a))).entityKey, null);
  await assert.rejects(data.plot(ref(a), 'value', 'value'), { kind: 'condition' });
  const b = await data.register('a.csv', { operationId: 'a' }, 'available', {}, declaration('a.csv'));
  assert.notEqual(a.id, b.id); assert.equal(a.version, b.version);
  await assert.rejects(data.rows(ref(b)), { kind: 'condition' });
  await assert.rejects(data.register('a.csv', { operationId: 'a' }, 'available', {}, d, 'a'.repeat(64)), { kind: 'stale' });
});
test('earlier snapshot bytes count toward storage budget and invalid UTF-8 stays intact', async () => {
  const root = await fs.mkdtemp(path.join(tmpdir(), 'rho-data-limit-'));
  const data = new Resources(root, 'test', { maxArtifactBytes: 8 });
  await fs.writeFile(path.join(root, 'a.txt'), 'first');
  const a = await data.register('a.txt', { operationId: 'a' }, 'partial');
  await fs.writeFile(path.join(root, 'a.txt'), 'second');
  await assert.rejects(data.register('a.txt', { operationId: 'a' }, 'partial'), { kind: 'limit' });
  assert.equal((await data.list())[0].version, a.version);
  await fs.writeFile(path.join(root, 'invalid.R'), Buffer.from([0xff, 0xfe]));
  await assert.rejects(new Documents(root).open('invalid.R', 'human'), { kind: 'invalid' });
  assert.deepEqual(await fs.readFile(path.join(root, 'invalid.R')), Buffer.from([0xff, 0xfe]));
});
test('empty and base-R requirements need no add-on package; script and argument refs are checked before dispatch', async () => {
  const root = await fs.mkdtemp(path.join(tmpdir(), 'rho-r-')), data = new Resources(root, 'test');
  const check = await checkRequirements(root, [{ package: 'stats', source: 'cran' }], process.env.RHO_RSCRIPT ?? 'Rscript');
  assert.equal(check.status, 'present'); assert.equal((await checkRequirements(root, [], process.env.RHO_RSCRIPT ?? 'Rscript')).status, 'present');
  assert.equal((await checkRequirements(root, [], path.join(root, 'absent-Rscript'))).status, 'unknown');
  const d = await new Documents(root).open('script.R', 'test');
  await assert.rejects(planExecution(root, { script: { kind: 'buffer', documentId: d.id, version: 9 }, artifacts: [], args: [], completion: null }, 'op', check.environment, data), { kind: 'stale' });
});
