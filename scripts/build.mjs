import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {verifySnapshot} from '../sdk/verify-snapshot.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [name, destination, mode] = process.argv.slice(2);
assert.match(name ?? '', /^[a-z][a-z0-9-]*$/);
assert.ok(destination, 'Usage: node scripts/build.mjs NAME NEW_DIRECTORY [--independent]');
assert.ok(mode === undefined || mode === '--independent');
const builder = path.join(root, `scripts/build-${name === 'annotations' ? 'annotation' : name}-plugin.mjs`);
assert.ok(fs.existsSync(builder), `Unknown plugin: ${name}`);
verifySnapshot(root);
execFileSync(process.execPath, [builder, path.resolve(destination), ...(mode ? [mode] : [])], {cwd: root, stdio: 'inherit'});
