// Checks agents.json and its icons, then writes them into src/catalog.generated.ts for tsc.
// An icon becomes a data: URL the page draws as an image, so nothing in it runs or loads;
// a file with scripts, event handlers or references outside itself is refused anyway.
import fs from 'node:fs/promises';

const root = new URL('..', import.meta.url);
const maxBytes = 32 * 1024;
const word = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const active = /<script|<foreignObject|<iframe|<image|<!ENTITY|<!DOCTYPE|javascript:|@import|\son[a-z]+\s*=|href\s*=\s*["'](?!#)|url\(\s*["']?(?!#)/i;

const catalog = JSON.parse(await fs.readFile(new URL('agents.json', root), 'utf8'));
const problems = [], ids = new Set(), aliases = new Map(), icons = [];
const fail = (entry, message) => problems.push(`${entry?.id ?? '(entry)'}: ${message}`);
for (const entry of catalog.agents ?? []) {
  if (typeof entry.id !== 'string' || !word.test(entry.id)) { fail(entry, 'id must be lowercase words joined by hyphens'); continue; }
  if (ids.has(entry.id)) fail(entry, 'id is used twice');
  ids.add(entry.id);
  for (const key of ['name', 'maker']) if (typeof entry[key] !== 'string' || !entry[key].trim() || entry[key].length > 64) fail(entry, key + ' must be 1–64 characters');
  for (const key of ['agent', 'ink']) if (typeof entry[key] !== 'boolean') fail(entry, key + ' must be true or false');
  if (!['lobehub', 'official'].includes(entry.source)) fail(entry, 'source must be lobehub or official');
  if (!Array.isArray(entry.aliases) || entry.aliases.length === 0) fail(entry, 'needs at least one alias');
  for (const alias of entry.aliases ?? []) {
    if (typeof alias !== 'string' || !word.test(alias)) fail(entry, `alias ${JSON.stringify(alias)} must be lowercase words joined by hyphens`);
    else if (aliases.has(alias)) fail(entry, `alias ${alias} is also ${aliases.get(alias)}'s`);
    else aliases.set(alias, entry.id);
  }
  let bytes;
  try { bytes = await fs.readFile(new URL(entry.icon, root)); } catch { fail(entry, `icon ${entry.icon} is missing`); continue; }
  if (bytes.length > maxBytes) { fail(entry, `icon is ${bytes.length} bytes; at most ${maxBytes}`); continue; }
  let src;
  if (/^icons\/[a-z0-9-]+\.svg$/.test(entry.icon)) {
    const svg = bytes.toString('utf8').trim();
    if (!/^<svg\b[^>]*\sxmlns="http:\/\/www\.w3\.org\/2000\/svg"/.test(svg) || !/<\/svg>$/.test(svg)) { fail(entry, 'icon is not one SVG element with its namespace'); continue; }
    if (active.test(svg)) { fail(entry, 'icon has scripts, handlers or references outside itself'); continue; }
    // Lobehub sizes its marks to the text (1em) with an inline style; the page sizes them instead.
    const sized = svg.replace(/^<svg\b[^>]*>/, tag => tag.replace(/\s(width|height|style)="[^"]*"/g, '').replace(/^<svg/, '<svg width="24" height="24"'));
    src = 'data:image/svg+xml,' + encodeURIComponent(sized);
  } else if (/^icons\/[a-z0-9-]+\.png$/.test(entry.icon)) {
    if (!bytes.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) { fail(entry, 'icon is not a PNG'); continue; }
    src = 'data:image/png;base64,' + bytes.toString('base64');
  } else { fail(entry, 'icon must be icons/<name>.svg or .png'); continue; }
  icons.push({ id: entry.id, name: entry.name, maker: entry.maker, agent: entry.agent, ink: entry.ink, aliases: entry.aliases, src });
}
const listed = new Set((catalog.agents ?? []).map(entry => entry.icon));
for (const file of await fs.readdir(new URL('icons/', root))) if (!file.startsWith('.') && !listed.has('icons/' + file)) problems.push(`icons/${file}: no entry uses it`);
if (problems.length) { process.stderr.write('agents.json:\n  ' + problems.join('\n  ') + '\n'); process.exit(1); }
await fs.writeFile(new URL('src/catalog.generated.ts', root), '// Generated by scripts/build.mjs from agents.json and icons/. Edit those instead.\n'
  + "import type { AgentIcon } from './types.js';\n\nexport const icons: readonly AgentIcon[] = " + JSON.stringify(icons, null, 1) + ';\n');
process.stdout.write(`agent-icons: ${icons.length} entries, ${aliases.size} aliases\n`);
